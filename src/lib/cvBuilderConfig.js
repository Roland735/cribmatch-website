export function getRoleConfig(roleId) {
  return ROLE_LIBRARY.find((role) => role.id === roleId) || ROLE_LIBRARY[ROLE_LIBRARY.length - 1];
}

export function optionsForRole(roleId, source, labels) {
  return getRoleConfig(roleId)[source].map((id) => ({ id, title: labels[id] || id }));
}

